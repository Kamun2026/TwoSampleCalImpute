#' TwoSampleCalImpute
#'
#' Two-Sample Calibrated Imputation for Incomplete Survey Data
#'
#' The `TwoSampleCalImpute` package provides computational
#' implementations of the Two-Sample Calibrated Imputation framework
#' for incomplete survey data when auxiliary information is available
#' from a separate reference sample.
#'
#' The package implements the computational chain:
#' \emph{Theory -> Algorithm -> R Implementation -> Validation ->
#' Simulation -> Reproducible Results}.
#'
#' The package is developed as part of the four-volume
#' `TwoSampleCalImpute` research programme.
#'
